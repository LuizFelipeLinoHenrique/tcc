CREATE TABLE IF NOT EXISTS public.fornecedores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    cnpj TEXT,
    email TEXT,
    telefone TEXT,
    endereco TEXT,
    contato TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Índices para otimização de busca
CREATE INDEX IF NOT EXISTS idx_fornecedores_nome ON public.fornecedores(nome);
CREATE INDEX IF NOT EXISTS idx_fornecedores_cnpj ON public.fornecedores(cnpj);
CREATE INDEX IF NOT EXISTS idx_fornecedores_email ON public.fornecedores(email);

-- Comentários na tabela e colunas
COMMENT ON TABLE public.fornecedores IS 'Tabela que armazena os fornecedores de produtos e serviços.';
COMMENT ON COLUMN public.fornecedores.id IS 'Identificador único do fornecedor.';
COMMENT ON COLUMN public.fornecedores.nome IS 'Nome fantasia ou razão social do fornecedor.';
COMMENT ON COLUMN public.fornecedores.cnpj IS 'CNPJ ou identificador fiscal do fornecedor.';
COMMENT ON COLUMN public.fornecedores.email IS 'E-mail de contato comercial do fornecedor.';
COMMENT ON COLUMN public.fornecedores.telefone IS 'Telefone ou WhatsApp de contato.';
COMMENT ON COLUMN public.fornecedores.endereco IS 'Endereço completo da sede do fornecedor.';
COMMENT ON COLUMN public.fornecedores.contato IS 'Nome do representante ou pessoa de contato.';

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.fornecedores ENABLE ROW LEVEL SECURITY;

-- Políticas de segurança RLS
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'fornecedores' AND policyname = 'Permitir acesso completo a usuários autenticados'
    ) THEN
        CREATE POLICY "Permitir acesso completo a usuários autenticados"
        ON public.fornecedores
        FOR ALL
        TO authenticated
        USING (true)
        WITH CHECK (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'fornecedores' AND policyname = 'Permitir leitura para anon'
    ) THEN
        CREATE POLICY "Permitir leitura para anon"
        ON public.fornecedores
        FOR SELECT
        TO anon
        USING (true);
    END IF;
END
$$;

-- Permissões para roles do Supabase
GRANT ALL ON TABLE public.fornecedores TO authenticated;
GRANT ALL ON TABLE public.fornecedores TO service_role;
GRANT SELECT ON TABLE public.fornecedores TO anon;
